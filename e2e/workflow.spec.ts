import { expect, goTo, isMobile, noHorizontalScroll, registerCenter, skipTour, test } from './fixtures'

test('ro\'yxatdan o\'tish → sozlash → mijoz → to\'lov va chek → chiqish → qayta kirish', async ({ page, consoleErrors }) => {
  await registerCenter(page)
  await page.getByRole('button', { name: 'Keyingi' }).click()
  await page.getByRole('button', { name: 'Ingliz tili' }).click()
  await page.getByLabel('Oylik narx').fill('650000')
  await page.getByRole('button', { name: "Qo'shish" }).click()
  await page.getByRole('button', { name: 'Keyingi' }).click()
  await page.getByRole('button', { name: "O'tkazib yuborish" }).click()
  await page.getByRole('button', { name: 'Boshlash' }).click()
  await skipTour(page)
  await expect(page.getByRole('heading', { level: 1, name: "Umumiy ko'rinish" })).toBeVisible()

  // Mijoz qo'shish (N tugmasi faqat kompyuterda)
  await goTo(page, 'Mijozlar va lidlar')
  await page.getByRole('button', { name: 'Yangi mijoz' }).first().click()
  const dialog = page.getByRole('dialog', { name: 'Yangi mijoz' })
  await dialog.getByLabel(/Ism familiya/).fill('Aziza Karimova')
  await dialog.getByLabel(/Telefon/).fill('901234567')
  await dialog.getByRole('button', { name: "Qo'shish" }).click()
  await expect(page.getByText('"Aziza Karimova" mijozlar bazasiga qo\'shildi')).toBeVisible()
  await noHorizontalScroll(page)

  // To'lov va chek
  await goTo(page, 'Moliya va kassa')
  await page.getByRole('button', { name: "To'lov qabul qilish" }).first().click()
  const pay = page.getByRole('dialog', { name: "To'lov qabul qilish" })
  await pay.getByLabel(/Summa/).fill('650000')
  await pay.getByLabel('Mijoz').fill('Aziza')
  await page.getByRole('option', { name: /Aziza Karimova/ }).click()
  await pay.getByRole('button', { name: 'Saqlash' }).click()
  await page.getByRole('region', { name: 'Bildirishnomalar' }).getByRole('button', { name: 'Chek' }).click()
  const receipt = page.getByRole('dialog', { name: "To'lov cheki" })
  await expect(receipt.getByText("Olti yuz ellik ming so'm")).toBeVisible()
  await expect(receipt.getByText('Qabul qildi: Dilshod Karimov')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(receipt).toHaveCount(0)
  await noHorizontalScroll(page)

  // Chiqish va qayta kirish — ma'lumot joyida
  await page.getByRole('button', { name: /^Profil:/ }).click()
  await page.getByRole('menuitem', { name: 'Chiqish' }).click()
  await page.getByLabel('Login').fill('direktor')
  await page.getByLabel('Parol', { exact: true }).fill('xato-parol')
  await page.getByRole('button', { name: 'Kirish' }).click()
  await expect(page.getByText(/Login yoki parol noto'g'ri/)).toBeVisible()
  await page.getByLabel('Parol', { exact: true }).fill('Toshkent2026')
  await page.getByRole('button', { name: 'Kirish' }).click()
  await goTo(page, 'Mijozlar va lidlar')
  await expect(page.getByRole('button', { name: 'Aziza Karimova', exact: true }).first()).toBeVisible()
  expect(consoleErrors).toEqual([])
})

test('xodim: administrator qo\'shadi → xodim vaqtinchalik parol bilan kiradi → yangi parol → faqat o\'z bo\'limlari', async ({ page }) => {
  test.skip(isMobile(page), 'kompyuterda yetarli')
  await registerCenter(page)
  await page.getByRole('button', { name: 'Keyinroq sozlayman' }).click()
  await skipTour(page)
  await goTo(page, 'Boshqaruv')
  await page.getByRole('button', { name: "Xodim qo'shish" }).click()
  const dialog = page.getByRole('dialog', { name: 'Yangi xodim' })
  await dialog.getByLabel(/Ism familiya/).fill('Malika Yusupova')
  await dialog.getByLabel(/^Login/).fill('malika')
  const password = await dialog.getByRole('textbox', { name: 'Vaqtinchalik parol' }).inputValue()
  await dialog.getByRole('button', { name: "Qo'shish" }).click()
  await page.getByRole('dialog', { name: "Xodim qo'shildi" }).getByRole('button', { name: 'Tayyor' }).click()

  await page.getByRole('button', { name: /^Profil:/ }).click()
  await page.getByRole('menuitem', { name: 'Chiqish' }).click()
  await page.getByLabel('Login').fill('malika')
  await page.getByLabel('Parol', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Kirish' }).click()
  await expect(page.getByRole('heading', { name: "Yangi parol o'rnating" })).toBeVisible()
  await page.getByRole('textbox', { name: /^Yangi parol/ }).fill('MalikaParol9')
  await page.getByLabel(/Parolni takrorlang/).fill('MalikaParol9')
  await page.getByRole('button', { name: 'Saqlash va davom etish' }).click()
  await skipTour(page)
  const nav = page.locator('.sidebar-nav')
  await expect(nav.getByRole('button', { name: 'Mijozlar va lidlar' })).toBeVisible()
  await expect(nav.getByRole('button', { name: 'Boshqaruv' })).toHaveCount(0)
  await expect(nav.getByRole('button', { name: 'Tahlil va hisobotlar' })).toHaveCount(0)
})

